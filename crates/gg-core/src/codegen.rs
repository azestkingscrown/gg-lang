pub fn compile_to_target(source: &str, target: EmitTarget, options: EmitOptions) -> EmitResult {
    let lex = tokenize(source);
    let program = parse(lex.tokens, lex.diagnostics, ParseOptions::default());
    let extension = match target {
        EmitTarget::Js => ".mjs".to_string(),
        EmitTarget::C => ".c".to_string(),
    };

    if !program.diagnostics.is_empty() {
        return EmitResult {
            target,
            code: String::new(),
            extension,
            diagnostics: program.diagnostics,
            warnings: Vec::new(),
        };
    }

    match target {
        EmitTarget::Js => {
            let code = emit_javascript(&program, &options).unwrap_or_default();
            EmitResult {
                target,
                code,
                extension,
                diagnostics: Vec::new(),
                warnings: Vec::new(),
            }
        }
        EmitTarget::C => {
            let (code, warnings) = emit_c_with_warnings(&program, &options).unwrap_or_default();
            EmitResult {
                target,
                code,
                extension,
                diagnostics: Vec::new(),
                warnings,
            }
        }
    }
}
