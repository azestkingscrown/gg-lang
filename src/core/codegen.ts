import { tokenize, truncateDisplay } from './lexer.js';
import { parse } from './parser.js';
import type { CompiledProgram, Diagnostic, Instruction } from './types.js';

export type EmitTarget = 'js' | 'c';

export interface EmitOptions {
  maxSteps?: number;
  maxStackSize?: number;
  maxMemorySize?: number;
  maxBigIntBits?: number;
  maxOutputLength?: number;
}

export interface EmitResult {
  target: EmitTarget;
  code: string;
  extension: '.mjs' | '.c';
  diagnostics: Diagnostic[];
  warnings: string[];
}

const DEFAULT_LIMITS = {
  maxSteps: 200_000,
  maxStackSize: 100_000,
  maxMemorySize: 100_000,
  maxBigIntBits: 65_536,
  maxOutputLength: 1_000_000,
} as const;

const INT64_MIN_BIGINT = -(1n << 63n);
const INT64_MAX_BIGINT = (1n << 63n) - 1n;

function resolveLimits(options: EmitOptions = {}) {
  const pick = (v: number | undefined, fallback: number): number =>
    typeof v === 'number' && Number.isFinite(v) && v >= 0 ? Math.floor(v) : fallback;
  return {
    maxSteps: pick(options.maxSteps, DEFAULT_LIMITS.maxSteps),
    maxStackSize: pick(options.maxStackSize, DEFAULT_LIMITS.maxStackSize),
    maxMemorySize: pick(options.maxMemorySize, DEFAULT_LIMITS.maxMemorySize),
    maxBigIntBits: pick(options.maxBigIntBits, DEFAULT_LIMITS.maxBigIntBits),
    maxOutputLength: pick(options.maxOutputLength, DEFAULT_LIMITS.maxOutputLength),
  };
}

function sanitizeComment(raw: string): string {
  return raw.replace(/\*\//g, '* /').replace(/[\r\n]/g, ' ');
}

function escapeCString(value: string): string {
  let out = '';
  for (let i = 0; i < value.length; i += 1) {
    const ch = value[i];
    if (ch === '\\') out += '\\\\';
    else if (ch === '"') out += '\\"';
    else if (ch === '\n') out += '\\n';
    else if (ch === '\r') out += '\\r';
    else if (ch === '\t') out += '\\t';
    else out += ch;
  }
  return out;
}

function programUsesStdin(instructions: Instruction[]): boolean {
  return instructions.some((instr) => instr.op === 'INPUT_INT' || instr.op === 'INPUT_CHAR');
}

export function emitJavaScript(program: CompiledProgram, options: EmitOptions = {}): string {
  if (program.diagnostics.length > 0) {
    throw new Error('Cannot emit JavaScript for a program with syntax diagnostics.');
  }

  const limits = resolveLimits(options);
  const instructions = program.instructions;
  const usesStdin = programUsesStdin(instructions);
  const lines: string[] = [];

  lines.push('#!/usr/bin/env node');
  lines.push('// Generated by gg-lang (줴줴랭) compiler');
  if (usesStdin) {
    lines.push("import fs from 'node:fs';");
  }
  lines.push('');
  lines.push(`const MAX_STEPS = ${limits.maxSteps};`);
  lines.push(`const MAX_STACK_SIZE = ${limits.maxStackSize};`);
  lines.push(`const MAX_MEMORY_SIZE = ${limits.maxMemorySize};`);
  lines.push(`const MAX_BIGINT_BITS = ${limits.maxBigIntBits};`);
  lines.push(`const MAX_OUTPUT_LENGTH = ${limits.maxOutputLength};`);
  if (usesStdin) {
    lines.push('const MAX_STDIN_INT_DIGITS = 20000;');
  }
  lines.push("const FAIL_SUFFIX = '터져서 없어짐 수고하세요';");
  lines.push('');
  lines.push('const stack = [];');
  lines.push('const memory = new Map();');
  lines.push("let output = '';");
  lines.push('let ip = 0;');
  lines.push('let steps = 0;');
  lines.push('let halted = false;');
  lines.push('let failed = false;');

  if (usesStdin) {
    lines.push("const stdinText = fs.readFileSync(0, 'utf8');");
    lines.push('let stdinPos = 0;');
  }

  lines.push('');
  lines.push('function bitLen(n) {');
  lines.push('  if (n === 0n) return 0;');
  lines.push('  const hex = (n < 0n ? -n : n).toString(16);');
  lines.push('  return (hex.length - 1) * 4 + (32 - Math.clz32(parseInt(hex[0], 16)));');
  lines.push('}');
  lines.push('');
  lines.push('function fail(code, message, line, col) {');
  lines.push('  if (!failed) {');
  lines.push('    failed = true;');
  lines.push('    halted = true;');
  lines.push('    const full = message.includes(FAIL_SUFFIX) ? message : `${message} — ${FAIL_SUFFIX}`;');
  lines.push('    if (output.length > 0) {');
  lines.push('      process.stdout.write(output);');
  lines.push("      if (!output.endsWith('\\n')) process.stdout.write('\\n');");
  lines.push("      output = '';");
  lines.push('    }');
  lines.push('    process.stderr.write(`[런타임 에러] ${line}:${col} (${code}) ${full}\\n`);');
  lines.push('    process.exitCode = 1;');
  lines.push('  }');
  lines.push('  return false;');
  lines.push('}');
  lines.push('');
  lines.push('function checkBits(val, line, col) {');
  lines.push('  if (bitLen(val) > MAX_BIGINT_BITS) {');
  lines.push("    return fail('RUNTIME_BIGINT_OVERFLOW', `지~랄 정수가 너무 커졌어요 (최대 ${MAX_BIGINT_BITS}비트)`, line, col);");
  lines.push('  }');
  lines.push('  return true;');
  lines.push('}');
  lines.push('');
  lines.push('function pushVal(val, line, col) {');
  lines.push('  if (stack.length >= MAX_STACK_SIZE) {');
  lines.push("    return fail('RUNTIME_STACK_OVERFLOW', `지~랄 스택이 너무 커졌어요 (최대 ${MAX_STACK_SIZE}개)`, line, col);");
  lines.push('  }');
  lines.push('  stack.push(val);');
  lines.push('  return true;');
  lines.push('}');
  lines.push('');
  lines.push('function appendOut(chunk, line, col) {');
  lines.push('  if (output.length + chunk.length > MAX_OUTPUT_LENGTH) {');
  lines.push("    return fail('RUNTIME_OUTPUT_LIMIT', `지~랄 출력 길이가 최대치(${MAX_OUTPUT_LENGTH}자)를 넘었어요.`, line, col);");
  lines.push('  }');
  lines.push('  output += chunk;');
  lines.push('  return true;');
  lines.push('}');

  if (usesStdin) {
    lines.push('');
    lines.push('function readInt(line, col) {');
    lines.push('  while (stdinPos < stdinText.length && /\\s/.test(stdinText[stdinPos])) stdinPos += 1;');
    lines.push('  if (stdinPos >= stdinText.length) {');
    lines.push("    fail('RUNTIME_STDIN_EOF', '예? 입력(stdin)이 비어서 정수를 읽을 수 없어요.', line, col);");
    lines.push('    return null;');
    lines.push('  }');
    lines.push('  const start = stdinPos;');
    lines.push('  while (stdinPos < stdinText.length && !/\\s/.test(stdinText[stdinPos])) stdinPos += 1;');
    lines.push('  const raw = stdinText.slice(start, stdinPos);');
    lines.push('  if (!/^[+-]?\\d+$/.test(raw)) {');
    lines.push("    fail('RUNTIME_INVALID_INT', `예? '${raw.slice(0, 40)}'은(는) 정수가 아닌데요?`, line, col);");
    lines.push('    return null;');
    lines.push('  }');
    lines.push('  if (raw.length > MAX_STDIN_INT_DIGITS) {');
    lines.push("    fail('RUNTIME_BIGINT_OVERFLOW', `지~랄 입력 정수가 너무 커요 (최대 ${MAX_STDIN_INT_DIGITS}자리)`, line, col);");
    lines.push('    return null;');
    lines.push('  }');
    lines.push('  const parsed = BigInt(raw);');
    lines.push('  if (!checkBits(parsed, line, col)) return null;');
    lines.push('  return parsed;');
    lines.push('}');
    lines.push('');
    lines.push('function readChar() {');
    lines.push('  if (stdinPos >= stdinText.length) return -1n;');
    lines.push('  const cp = stdinText.codePointAt(stdinPos);');
    lines.push('  stdinPos += cp > 0xffff ? 2 : 1;');
    lines.push('  return BigInt(cp);');
    lines.push('}');
  }

  lines.push('');
  const locsLiteral = JSON.stringify(instructions.map((instr) => [instr.token.line, instr.token.column]));
  lines.push(`const LOCS = ${locsLiteral};`);
  lines.push(`while (!halted && ip >= 0 && ip < ${instructions.length}) {`);
  lines.push('  if (steps >= MAX_STEPS) {');
  lines.push('    const loc = LOCS[ip] || [1, 1];');
  lines.push("    fail('RUNTIME_STEP_LIMIT', `지~랄 실행 횟수가 최대치(${MAX_STEPS}스텝)를 넘었어요! 무한 루프에 빠진 것 같네요.`, loc[0], loc[1]);");
  lines.push('    break;');
  lines.push('  }');
  lines.push('  switch (ip) {');

  for (let i = 0; i < instructions.length; i += 1) {
    const instr = instructions[i];
    const { line, column, raw } = instr.token;
    const rawStr = JSON.stringify(raw);
    const nextIp = i + 1;
    lines.push(`    case ${i}: { // L${line}:${column} ${sanitizeComment(raw)}`);

    switch (instr.op) {
      case 'PUSH': {
        const val = (instr.operand as bigint).toString();
        lines.push(`      const v = ${val}n;`);
        lines.push(`      if (!checkBits(v, ${line}, ${column}) || !pushVal(v, ${line}, ${column})) break;`);
        lines.push(`      ip = ${nextIp};`);
        break;
      }
      case 'POP':
        lines.push(`      if (stack.length < 1) { fail('RUNTIME_STACK_UNDERFLOW', '예? 스택에 아무것도 없는데요?', ${line}, ${column}); break; }`);
        lines.push('      stack.pop();');
        lines.push(`      ip = ${nextIp};`);
        break;
      case 'DUP':
        lines.push(`      if (stack.length < 1) { fail('RUNTIME_STACK_UNDERFLOW', '예? 스택에 아무것도 없는데요?', ${line}, ${column}); break; }`);
        lines.push(`      if (!pushVal(stack[stack.length - 1], ${line}, ${column})) break;`);
        lines.push(`      ip = ${nextIp};`);
        break;
      case 'SWAP':
        lines.push(`      if (stack.length < 2) { fail('RUNTIME_STACK_UNDERFLOW', '예? 스택에 값이 최소 2개는 있어야 ' + ${rawStr} + '을(를) 할 수 있어요.', ${line}, ${column}); break; }`);
        lines.push('      const b = stack.pop();');
        lines.push('      const a = stack.pop();');
        lines.push('      stack.push(b, a);');
        lines.push(`      ip = ${nextIp};`);
        break;
      case 'OVER':
        lines.push(`      if (stack.length < 2) { fail('RUNTIME_STACK_UNDERFLOW', '예? ' + ${rawStr} + '(OVER)을 하려면 스택에 값이 최소 2개 있어야 해요.', ${line}, ${column}); break; }`);
        lines.push(`      if (!pushVal(stack[stack.length - 2], ${line}, ${column})) break;`);
        lines.push(`      ip = ${nextIp};`);
        break;
      case 'ROT':
        lines.push(`      if (stack.length < 3) { fail('RUNTIME_STACK_UNDERFLOW', '예? ' + ${rawStr} + '(ROT)을 하려면 스택에 값이 최소 3개 있어야 해요.', ${line}, ${column}); break; }`);
        lines.push('      const c = stack.pop();');
        lines.push('      const b = stack.pop();');
        lines.push('      const a = stack.pop();');
        lines.push('      stack.push(b, c, a);');
        lines.push(`      ip = ${nextIp};`);
        break;
      case 'DEPTH':
        lines.push(`      if (!pushVal(BigInt(stack.length), ${line}, ${column})) break;`);
        lines.push(`      ip = ${nextIp};`);
        break;
      case 'ADD':
      case 'SUB':
      case 'MUL': {
        lines.push(`      if (stack.length < 2) { fail('RUNTIME_STACK_UNDERFLOW', '예? 스택에 값이 최소 2개는 있어야 ' + ${rawStr} + '을(를) 할 수 있어요.', ${line}, ${column}); break; }`);
        lines.push('      const a = stack[stack.length - 2];');
        lines.push('      const b = stack[stack.length - 1];');
        if (instr.op === 'MUL') {
          lines.push(`      if (a !== 0n && b !== 0n && bitLen(a) + bitLen(b) - 1 > MAX_BIGINT_BITS) { fail('RUNTIME_BIGINT_OVERFLOW', \`지~랄 정수가 너무 커졌어요 (최대 \${MAX_BIGINT_BITS}비트)\`, ${line}, ${column}); break; }`);
        }
        const opExpr = instr.op === 'ADD' ? 'a + b' : instr.op === 'SUB' ? 'a - b' : 'a * b';
        lines.push(`      const res = ${opExpr};`);
        lines.push(`      if (!checkBits(res, ${line}, ${column})) break;`);
        lines.push('      stack.length -= 2;');
        lines.push('      stack.push(res);');
        lines.push(`      ip = ${nextIp};`);
        break;
      }
      case 'DIV':
      case 'MOD': {
        lines.push(`      if (stack.length < 2) { fail('RUNTIME_STACK_UNDERFLOW', '예? 스택에 값이 최소 2개는 있어야 ' + ${rawStr} + '을(를) 할 수 있어요.', ${line}, ${column}); break; }`);
        lines.push('      const a = stack[stack.length - 2];');
        lines.push('      const b = stack[stack.length - 1];');
        lines.push(`      if (b === 0n) { fail('RUNTIME_DIV_ZERO', '지~랄 0으로 어떻게 나눠요', ${line}, ${column}); break; }`);
        lines.push('      stack.length -= 2;');
        lines.push(`      stack.push(${instr.op === 'DIV' ? 'a / b' : 'a % b'});`);
        lines.push(`      ip = ${nextIp};`);
        break;
      }
      case 'EQ':
      case 'LT':
      case 'GT': {
        const cmp = instr.op === 'EQ' ? '===' : instr.op === 'LT' ? '<' : '>';
        lines.push(`      if (stack.length < 2) { fail('RUNTIME_STACK_UNDERFLOW', '예? 스택에 값이 최소 2개는 있어야 ' + ${rawStr} + '을(를) 할 수 있어요.', ${line}, ${column}); break; }`);
        lines.push('      const b = stack.pop();');
        lines.push('      const a = stack.pop();');
        lines.push(`      stack.push(a ${cmp} b ? 1n : 0n);`);
        lines.push(`      ip = ${nextIp};`);
        break;
      }
      case 'NOT':
        lines.push(`      if (stack.length < 1) { fail('RUNTIME_STACK_UNDERFLOW', '예? 스택에 아무것도 없는데요?', ${line}, ${column}); break; }`);
        lines.push('      stack.push(stack.pop() === 0n ? 1n : 0n);');
        lines.push(`      ip = ${nextIp};`);
        break;
      case 'STORE':
        lines.push(`      if (stack.length < 2) { fail('RUNTIME_STACK_UNDERFLOW', '예? 스택에 값이 최소 2개는 있어야 ' + ${rawStr} + '을(를) 할 수 있어요.', ${line}, ${column}); break; }`);
        lines.push('      const val = stack[stack.length - 2];');
        lines.push('      const addr = stack[stack.length - 1];');
        lines.push(`      if (!memory.has(addr) && memory.size >= MAX_MEMORY_SIZE) { fail('RUNTIME_MEMORY_OVERFLOW', \`지~랄 메모리가 너무 많이 찼어요 (최대 \${MAX_MEMORY_SIZE}칸)\`, ${line}, ${column}); break; }`);
        lines.push('      stack.length -= 2;');
        lines.push('      memory.set(addr, val);');
        lines.push(`      ip = ${nextIp};`);
        break;
      case 'LOAD':
        lines.push(`      if (stack.length < 1) { fail('RUNTIME_STACK_UNDERFLOW', '예? 스택에 아무것도 없는데요?', ${line}, ${column}); break; }`);
        lines.push('      const addr = stack.pop();');
        lines.push('      stack.push(memory.get(addr) ?? 0n);');
        lines.push(`      ip = ${nextIp};`);
        break;
      case 'INPUT_INT':
        lines.push(`      const v = readInt(${line}, ${column});`);
        lines.push(`      if (v === null || !pushVal(v, ${line}, ${column})) break;`);
        lines.push(`      ip = ${nextIp};`);
        break;
      case 'INPUT_CHAR':
        lines.push(`      if (!pushVal(readChar(), ${line}, ${column})) break;`);
        lines.push(`      ip = ${nextIp};`);
        break;
      case 'PRINT_INT':
        lines.push(`      if (stack.length < 1) { fail('RUNTIME_STACK_UNDERFLOW', '예? 스택에 아무것도 없는데요?', ${line}, ${column}); break; }`);
        lines.push(`      if (!appendOut(stack[stack.length - 1].toString(), ${line}, ${column})) break;`);
        lines.push('      stack.pop();');
        lines.push(`      ip = ${nextIp};`);
        break;
      case 'PRINT_INT_LN':
        lines.push(`      if (stack.length < 1) { fail('RUNTIME_STACK_UNDERFLOW', '예? 스택에 아무것도 없는데요?', ${line}, ${column}); break; }`);
        lines.push(`      if (!appendOut(stack[stack.length - 1].toString() + '\\n', ${line}, ${column})) break;`);
        lines.push('      stack.pop();');
        lines.push(`      ip = ${nextIp};`);
        break;
      case 'PRINT_CHAR':
        lines.push(`      if (stack.length < 1) { fail('RUNTIME_STACK_UNDERFLOW', '예? 스택에 아무것도 없는데요?', ${line}, ${column}); break; }`);
        lines.push('      const cp = stack[stack.length - 1];');
        lines.push(`      if (cp < 0n || cp > 0x10ffffn || (cp >= 0xd800n && cp <= 0xdfffn)) { fail('RUNTIME_INVALID_CODEPOINT', '지~랄 유효한 유니코드 문자가 아니에요.', ${line}, ${column}); break; }`);
        lines.push(`      if (!appendOut(String.fromCodePoint(Number(cp)), ${line}, ${column})) break;`);
        lines.push('      stack.pop();');
        lines.push(`      ip = ${nextIp};`);
        break;
      case 'JZ':
        lines.push(`      if (stack.length < 1) { fail('RUNTIME_STACK_UNDERFLOW', '예? 스택에 아무것도 없는데요?', ${line}, ${column}); break; }`);
        lines.push(`      ip = stack.pop() === 0n ? ${Number(instr.operand)} : ${nextIp};`);
        break;
      case 'JZ_PEEK':
        lines.push(`      if (stack.length < 1) { fail('RUNTIME_STACK_UNDERFLOW', "예? 반복문('아뇨아뇨~') 조건을 확인할 값이 스택에 없어요.", ${line}, ${column}); break; }`);
        lines.push(`      ip = stack[stack.length - 1] === 0n ? ${Number(instr.operand)} : ${nextIp};`);
        break;
      case 'JMP':
        lines.push(`      ip = ${Number(instr.operand)};`);
        break;
      case 'HALT':
        lines.push('      halted = true;');
        break;
    }

    lines.push('      steps += 1;');
    lines.push('      break;');
    lines.push('    }');
  }

  lines.push('  }');
  lines.push('}');
  lines.push('');
  lines.push('if (!failed && output.length > 0) {');
  lines.push('  process.stdout.write(output);');
  lines.push('}');
  lines.push('');

  return lines.join('\n');
}

function formatCInt64Literal(val: bigint): { expr: string; overflow: boolean } {
  if (val < INT64_MIN_BIGINT || val > INT64_MAX_BIGINT) {
    return { expr: '0', overflow: true };
  }
  if (val === INT64_MIN_BIGINT) {
    return { expr: 'INT64_MIN', overflow: false };
  }
  return { expr: `INT64_C(${val.toString()})`, overflow: false };
}

export function emitCWithWarnings(
  program: CompiledProgram,
  options: EmitOptions = {},
): { code: string; warnings: string[] } {
  if (program.diagnostics.length > 0) {
    throw new Error('Cannot emit C code for a program with syntax diagnostics.');
  }

  const limits = resolveLimits(options);
  const instructions = program.instructions;
  const warnings: string[] = [];
  const lines: string[] = [];

  lines.push('/* Generated by gg-lang (줴줴랭) compiler - ISO C11 */');
  lines.push('#include <ctype.h>');
  lines.push('#include <inttypes.h>');
  lines.push('#include <stdbool.h>');
  lines.push('#include <stdint.h>');
  lines.push('#include <stdio.h>');
  lines.push('#include <stdlib.h>');
  lines.push('#include <string.h>');
  lines.push('');
  lines.push(`#define GG_MAX_STEPS ((uint64_t)${limits.maxSteps}ULL)`);
  lines.push(`#define GG_MAX_STACK ((size_t)${limits.maxStackSize}U)`);
  lines.push(`#define GG_MAX_MEMORY ((size_t)${limits.maxMemorySize}U)`);
  lines.push(`#define GG_MAX_OUTPUT ((size_t)${limits.maxOutputLength}U)`);
  lines.push('#define GG_FAIL_SUFFIX "터져서 없어짐 수고하세요"');
  lines.push('');
  lines.push(`typedef struct { int64_t *data; size_t len; size_t cap; } gg_stack_t;`);
  lines.push('typedef struct { int64_t key; int64_t val; uint8_t state; } gg_mem_entry_t;');
  lines.push('typedef struct { gg_mem_entry_t *entries; size_t cap; size_t len; } gg_mem_t;');
  lines.push('typedef struct { bool halted; bool failed; size_t out_units; int last_char; bool has_out; } gg_rt_t;');
  lines.push('');

  lines.push('static inline bool gg_fail(gg_rt_t *rt, const char *code, const char *msg, int line, int col) {');
  lines.push('  if (!rt->failed) {');
  lines.push('    rt->failed = true;');
  lines.push('    rt->halted = true;');
  lines.push("    if (rt->has_out && rt->last_char != '\\n') { putchar('\\n'); }");
  lines.push('    fflush(stdout);');
  lines.push('    fprintf(stderr, "[런타임 에러] %d:%d (%s) %s — %s\\n", line, col, code, msg, GG_FAIL_SUFFIX);');
  lines.push('  }');
  lines.push('  return false;');
  lines.push('}');
  lines.push('');

  lines.push('static inline bool gg_push(gg_stack_t *s, gg_rt_t *rt, int64_t v, int line, int col) {');
  lines.push('  if (s->len >= GG_MAX_STACK) { return gg_fail(rt, "RUNTIME_STACK_OVERFLOW", "지~랄 스택이 너무 커졌어요", line, col); }');
  lines.push('  if (s->len == s->cap) {');
  lines.push('    size_t ncap = s->cap ? s->cap * 2 : 64;');
  lines.push('    if (ncap > GG_MAX_STACK) ncap = GG_MAX_STACK;');
  lines.push('    int64_t *nd = (int64_t *)realloc(s->data, ncap * sizeof(int64_t));');
  lines.push('    if (!nd) { return gg_fail(rt, "RUNTIME_STACK_OVERFLOW", "메모리 할당 실패", line, col); }');
  lines.push('    s->data = nd;');
  lines.push('    s->cap = ncap;');
  lines.push('  }');
  lines.push('  s->data[s->len++] = v;');
  lines.push('  return true;');
  lines.push('}');
  lines.push('');

  lines.push('static inline bool gg_require(const gg_stack_t *s, gg_rt_t *rt, size_t n, int line, int col) {');
  lines.push('  if (s->len < n) {');
  lines.push('    return gg_fail(rt, "RUNTIME_STACK_UNDERFLOW", "예? 스택에 값이 부족해요", line, col);');
  lines.push('  }');
  lines.push('  return true;');
  lines.push('}');
  lines.push('');

  lines.push('static inline size_t gg_hash_i64(int64_t key, size_t mask) {');
  lines.push('  uint64_t x = (uint64_t)key;');
  lines.push('  x ^= x >> 30;');
  lines.push('  x *= UINT64_C(0xbf58476d1ce4e5b9);');
  lines.push('  x ^= x >> 27;');
  lines.push('  x *= UINT64_C(0x94d049bb133111eb);');
  lines.push('  x ^= x >> 31;');
  lines.push('  return (size_t)(x & (uint64_t)mask);');
  lines.push('}');
  lines.push('');

  lines.push('static inline int64_t gg_mem_get(const gg_mem_t *m, int64_t key) {');
  lines.push('  if (!m->entries || m->cap == 0) return 0;');
  lines.push('  size_t mask = m->cap - 1;');
  lines.push('  size_t idx = gg_hash_i64(key, mask);');
  lines.push('  while (m->entries[idx].state) {');
  lines.push('    if (m->entries[idx].key == key) return m->entries[idx].val;');
  lines.push('    idx = (idx + 1) & mask;');
  lines.push('  }');
  lines.push('  return 0;');
  lines.push('}');
  lines.push('');

  lines.push('static inline bool gg_mem_rehash(gg_mem_t *m, size_t ncap) {');
  lines.push('  gg_mem_entry_t *ne = (gg_mem_entry_t *)calloc(ncap, sizeof(gg_mem_entry_t));');
  lines.push('  if (!ne) return false;');
  lines.push('  size_t mask = ncap - 1;');
  lines.push('  for (size_t i = 0; i < m->cap; i++) {');
  lines.push('    if (m->entries[i].state) {');
  lines.push('      size_t idx = gg_hash_i64(m->entries[i].key, mask);');
  lines.push('      while (ne[idx].state) idx = (idx + 1) & mask;');
  lines.push('      ne[idx] = m->entries[i];');
  lines.push('    }');
  lines.push('  }');
  lines.push('  free(m->entries);');
  lines.push('  m->entries = ne;');
  lines.push('  m->cap = ncap;');
  lines.push('  return true;');
  lines.push('}');
  lines.push('');

  lines.push('static inline bool gg_mem_set(gg_mem_t *m, gg_rt_t *rt, int64_t key, int64_t val, int line, int col) {');
  lines.push('  if (m->cap == 0 && !gg_mem_rehash(m, 64)) return gg_fail(rt, "RUNTIME_MEMORY_OVERFLOW", "메모리 할당 실패", line, col);');
  lines.push('  size_t mask = m->cap - 1;');
  lines.push('  size_t idx = gg_hash_i64(key, mask);');
  lines.push('  while (m->entries[idx].state) {');
  lines.push('    if (m->entries[idx].key == key) { m->entries[idx].val = val; return true; }');
  lines.push('    idx = (idx + 1) & mask;');
  lines.push('  }');
  lines.push('  if (m->len >= GG_MAX_MEMORY) return gg_fail(rt, "RUNTIME_MEMORY_OVERFLOW", "지~랄 메모리가 너무 많이 찼어요", line, col);');
  lines.push('  if ((m->len + 1) * 10 >= m->cap * 7) {');
  lines.push('    if (!gg_mem_rehash(m, m->cap * 2)) return gg_fail(rt, "RUNTIME_MEMORY_OVERFLOW", "메모리 재할당 실패", line, col);');
  lines.push('    mask = m->cap - 1;');
  lines.push('    idx = gg_hash_i64(key, mask);');
  lines.push('    while (m->entries[idx].state) idx = (idx + 1) & mask;');
  lines.push('  }');
  lines.push('  m->entries[idx].key = key;');
  lines.push('  m->entries[idx].val = val;');
  lines.push('  m->entries[idx].state = 1;');
  lines.push('  m->len++;');
  lines.push('  return true;');
  lines.push('}');
  lines.push('');

  lines.push('static inline bool gg_add(int64_t a, int64_t b, int64_t *out) {');
  lines.push('  if ((b > 0 && a > INT64_MAX - b) || (b < 0 && a < INT64_MIN - b)) return false;');
  lines.push('  *out = a + b; return true;');
  lines.push('}');
  lines.push('');
  lines.push('static inline bool gg_sub(int64_t a, int64_t b, int64_t *out) {');
  lines.push('  if ((b < 0 && a > INT64_MAX + b) || (b > 0 && a < INT64_MIN + b)) return false;');
  lines.push('  *out = a - b; return true;');
  lines.push('}');
  lines.push('');
  lines.push('static inline bool gg_mul(int64_t a, int64_t b, int64_t *out) {');
  lines.push('  if (a == 0 || b == 0) { *out = 0; return true; }');
  lines.push('  if (a > 0) {');
  lines.push('    if (b > 0) { if (a > INT64_MAX / b) return false; }');
  lines.push('    else { if (b < INT64_MIN / a) return false; }');
  lines.push('  } else {');
  lines.push('    if (b > 0) { if (a < INT64_MIN / b) return false; }');
  lines.push('    else { if (b < INT64_MAX / a) return false; }');
  lines.push('  }');
  lines.push('  *out = a * b; return true;');
  lines.push('}');
  lines.push('');

  lines.push('static inline bool gg_print_str(gg_rt_t *rt, const char *s, size_t units, int line, int col) {');
  lines.push('  if (rt->out_units + units > GG_MAX_OUTPUT) {');
  lines.push('    return gg_fail(rt, "RUNTIME_OUTPUT_LIMIT", "지~랄 출력 길이가 최대치를 넘었어요", line, col);');
  lines.push('  }');
  lines.push('  size_t blen = strlen(s);');
  lines.push('  if (blen > 0) {');
  lines.push('    fwrite(s, 1, blen, stdout);');
  lines.push('    rt->last_char = (unsigned char)s[blen - 1];');
  lines.push('    rt->has_out = true;');
  lines.push('  }');
  lines.push('  rt->out_units += units;');
  lines.push('  return true;');
  lines.push('}');
  lines.push('');

  lines.push('static inline bool gg_print_int(gg_rt_t *rt, int64_t v, bool newline, int line, int col) {');
  lines.push('  char buf[32];');
  lines.push('  int n = snprintf(buf, sizeof(buf), newline ? "%" PRId64 "\\n" : "%" PRId64, v);');
  lines.push('  if (n < 0) return gg_fail(rt, "RUNTIME_OUTPUT_LIMIT", "출력 포맷 실패", line, col);');
  lines.push('  return gg_print_str(rt, buf, (size_t)n, line, col);');
  lines.push('}');
  lines.push('');

  lines.push('static inline bool gg_print_char(gg_rt_t *rt, int64_t cp, int line, int col) {');
  lines.push('  if (cp < 0 || cp > 0x10FFFF || (cp >= 0xD800 && cp <= 0xDFFF)) {');
  lines.push('    return gg_fail(rt, "RUNTIME_INVALID_CODEPOINT", "지~랄 유효한 유니코드 문자가 아니에요", line, col);');
  lines.push('  }');
  lines.push('  char utf8[5];');
  lines.push('  size_t len = 0;');
  lines.push('  uint32_t u = (uint32_t)cp;');
  lines.push('  if (u <= 0x7F) { utf8[len++] = (char)u; }');
  lines.push('  else if (u <= 0x7FF) { utf8[len++] = (char)(0xC0 | (u >> 6)); utf8[len++] = (char)(0x80 | (u & 0x3F)); }');
  lines.push('  else if (u <= 0xFFFF) { utf8[len++] = (char)(0xE0 | (u >> 12)); utf8[len++] = (char)(0x80 | ((u >> 6) & 0x3F)); utf8[len++] = (char)(0x80 | (u & 0x3F)); }');
  lines.push('  else { utf8[len++] = (char)(0xF0 | (u >> 18)); utf8[len++] = (char)(0x80 | ((u >> 12) & 0x3F)); utf8[len++] = (char)(0x80 | ((u >> 6) & 0x3F)); utf8[len++] = (char)(0x80 | (u & 0x3F)); }');
  lines.push("  utf8[len] = '\\0';");
  lines.push('  return gg_print_str(rt, utf8, u > 0xFFFF ? 2 : 1, line, col);');
  lines.push('}');
  lines.push('');

  lines.push('static inline bool gg_read_int(gg_rt_t *rt, int64_t *out, int line, int col) {');
  lines.push('  int c;');
  lines.push('  do { c = fgetc(stdin); } while (c != EOF && isspace((unsigned char)c));');
  lines.push('  if (c == EOF) return gg_fail(rt, "RUNTIME_STDIN_EOF", "예? 입력(stdin)이 비어서 정수를 읽을 수 없어요", line, col);');
  lines.push('  bool neg = false;');
  lines.push("  if (c == '-' || c == '+') { neg = (c == '-'); c = fgetc(stdin); if (c == EOF || isspace((unsigned char)c)) return gg_fail(rt, \"RUNTIME_INVALID_INT\", \"예? 정수가 아닌데요?\", line, col); }");
  lines.push('  uint64_t acc = 0;');
  lines.push('  uint64_t limit = neg ? ((uint64_t)INT64_MAX + 1ULL) : (uint64_t)INT64_MAX;');
  lines.push('  size_t digits = 0;');
  lines.push('  while (c != EOF && !isspace((unsigned char)c)) {');
  lines.push("    if (c < '0' || c > '9') return gg_fail(rt, \"RUNTIME_INVALID_INT\", \"예? 정수가 아닌데요?\", line, col);");
  lines.push("    uint64_t d = (uint64_t)(c - '0');");
  lines.push('    if (acc > (limit - d) / 10ULL) return gg_fail(rt, "RUNTIME_BIGINT_OVERFLOW", "지~랄 입력 정수가 int64 범위를 넘었어요", line, col);');
  lines.push('    acc = acc * 10ULL + d;');
  lines.push('    digits++;');
  lines.push('    if (digits > 20000) return gg_fail(rt, "RUNTIME_BIGINT_OVERFLOW", "지~랄 입력 정수가 너무 커요", line, col);');
  lines.push('    c = fgetc(stdin);');
  lines.push('  }');
  lines.push('  if (neg) { *out = (acc == (uint64_t)INT64_MAX + 1ULL) ? INT64_MIN : -(int64_t)acc; }');
  lines.push('  else { *out = (int64_t)acc; }');
  lines.push('  return true;');
  lines.push('}');
  lines.push('');

  lines.push('static inline bool gg_read_char(gg_rt_t *rt, int64_t *out, int line, int col) {');
  lines.push('  int b0 = fgetc(stdin);');
  lines.push('  if (b0 == EOF) { *out = -1; return true; }');
  lines.push('  uint8_t u0 = (uint8_t)b0;');
  lines.push('  if (u0 < 0x80) { *out = (int64_t)u0; return true; }');
  lines.push('  int extra = 0; uint32_t cp = 0; uint32_t min_cp = 0;');
  lines.push('  if ((u0 & 0xE0) == 0xC0) { extra = 1; cp = u0 & 0x1F; min_cp = 0x80; }');
  lines.push('  else if ((u0 & 0xF0) == 0xE0) { extra = 2; cp = u0 & 0x0F; min_cp = 0x800; }');
  lines.push('  else if ((u0 & 0xF8) == 0xF0) { extra = 3; cp = u0 & 0x07; min_cp = 0x10000; }');
  lines.push('  else { return gg_fail(rt, "RUNTIME_INVALID_CODEPOINT", "잘못된 UTF-8 입력입니다", line, col); }');
  lines.push('  for (int i = 0; i < extra; i++) {');
  lines.push('    int bi = fgetc(stdin);');
  lines.push('    if (bi == EOF || ((uint8_t)bi & 0xC0) != 0x80) return gg_fail(rt, "RUNTIME_INVALID_CODEPOINT", "잘못된 UTF-8 입력입니다", line, col);');
  lines.push('    cp = (cp << 6) | ((uint8_t)bi & 0x3F);');
  lines.push('  }');
  lines.push('  if (cp < min_cp || cp > 0x10FFFF || (cp >= 0xD800 && cp <= 0xDFFF)) {');
  lines.push('    return gg_fail(rt, "RUNTIME_INVALID_CODEPOINT", "잘못된 UTF-8 입력입니다", line, col);');
  lines.push('  }');
  lines.push('  *out = (int64_t)cp;');
  lines.push('  return true;');
  lines.push('}');
  lines.push('');

  lines.push('int main(void) {');
  lines.push('  gg_stack_t s = { NULL, 0, 0 };');
  lines.push('  gg_mem_t mem = { NULL, 0, 0 };');
  lines.push("  gg_rt_t rt = { false, false, 0, '\\n', false };");
  lines.push('  size_t ip = 0;');
  lines.push('  uint64_t steps = 0;');
  lines.push('  static const int line_tbl[] = {');
  lines.push(
    `    ${instructions.length > 0 ? instructions.map((ins) => ins.token.line).join(', ') : '1'}`,
  );
  lines.push('  };');
  lines.push('  static const int col_tbl[] = {');
  lines.push(
    `    ${instructions.length > 0 ? instructions.map((ins) => ins.token.column).join(', ') : '1'}`,
  );
  lines.push('  };');
  lines.push('');
  lines.push(`  while (!rt.halted && ip < ${instructions.length}) {`);
  lines.push('    if (steps >= GG_MAX_STEPS) {');
  lines.push('      gg_fail(&rt, "RUNTIME_STEP_LIMIT", "지~랄 실행 횟수가 최대치를 넘었어요", line_tbl[ip], col_tbl[ip]);');
  lines.push('      break;');
  lines.push('    }');
  lines.push('    switch (ip) {');

  for (let i = 0; i < instructions.length; i += 1) {
    const instr = instructions[i];
    const { line, column, raw } = instr.token;
    const nextIp = i + 1;
    lines.push(`      case ${i}: { /* L${line}:${column} ${sanitizeComment(raw)} */`);

    switch (instr.op) {
      case 'PUSH': {
        const val = instr.operand as bigint;
        const lit = formatCInt64Literal(val);
        if (lit.overflow) {
          const preview = truncateDisplay(val.toString());
          warnings.push(
            `C 타깃은 int64_t를 사용하므로 L${line}:${column} 리터럴 '${preview}'이(가) 64비트 범위를 초과합니다.`,
          );
          lines.push(
            `        gg_fail(&rt, "RUNTIME_BIGINT_OVERFLOW", "지~랄 정수가 64비트 범위를 초과했어요 (${escapeCString(preview)})", ${line}, ${column});`,
          );
        } else {
          lines.push(`        if (!gg_push(&s, &rt, ${lit.expr}, ${line}, ${column})) break;`);
          lines.push(`        ip = ${nextIp};`);
        }
        break;
      }
      case 'POP':
        lines.push(`        if (!gg_require(&s, &rt, 1, ${line}, ${column})) break;`);
        lines.push('        s.len--;');
        lines.push(`        ip = ${nextIp};`);
        break;
      case 'DUP':
        lines.push(`        if (!gg_require(&s, &rt, 1, ${line}, ${column})) break;`);
        lines.push(`        if (!gg_push(&s, &rt, s.data[s.len - 1], ${line}, ${column})) break;`);
        lines.push(`        ip = ${nextIp};`);
        break;
      case 'SWAP':
        lines.push(`        if (!gg_require(&s, &rt, 2, ${line}, ${column})) break;`);
        lines.push('        { int64_t t = s.data[s.len - 1]; s.data[s.len - 1] = s.data[s.len - 2]; s.data[s.len - 2] = t; }');
        lines.push(`        ip = ${nextIp};`);
        break;
      case 'OVER':
        lines.push(`        if (!gg_require(&s, &rt, 2, ${line}, ${column})) break;`);
        lines.push(`        if (!gg_push(&s, &rt, s.data[s.len - 2], ${line}, ${column})) break;`);
        lines.push(`        ip = ${nextIp};`);
        break;
      case 'ROT':
        lines.push(`        if (!gg_require(&s, &rt, 3, ${line}, ${column})) break;`);
        lines.push('        { int64_t a = s.data[s.len - 3], b = s.data[s.len - 2], c = s.data[s.len - 1]; s.data[s.len - 3] = b; s.data[s.len - 2] = c; s.data[s.len - 1] = a; }');
        lines.push(`        ip = ${nextIp};`);
        break;
      case 'DEPTH':
        lines.push(`        if (!gg_push(&s, &rt, (int64_t)s.len, ${line}, ${column})) break;`);
        lines.push(`        ip = ${nextIp};`);
        break;
      case 'ADD':
      case 'SUB':
      case 'MUL': {
        const fn = instr.op === 'ADD' ? 'gg_add' : instr.op === 'SUB' ? 'gg_sub' : 'gg_mul';
        lines.push(`        if (!gg_require(&s, &rt, 2, ${line}, ${column})) break;`);
        lines.push('        int64_t res = 0;');
        lines.push(`        if (!${fn}(s.data[s.len - 2], s.data[s.len - 1], &res)) { gg_fail(&rt, "RUNTIME_BIGINT_OVERFLOW", "지~랄 정수가 64비트 범위를 초과했어요", ${line}, ${column}); break; }`);
        lines.push('        s.len--; s.data[s.len - 1] = res;');
        lines.push(`        ip = ${nextIp};`);
        break;
      }
      case 'DIV':
      case 'MOD':
        lines.push(`        if (!gg_require(&s, &rt, 2, ${line}, ${column})) break;`);
        lines.push('        { int64_t a = s.data[s.len - 2], b = s.data[s.len - 1];');
        lines.push(`          if (b == 0) { gg_fail(&rt, "RUNTIME_DIV_ZERO", "지~랄 0으로 어떻게 나눠요", ${line}, ${column}); break; }`);
        if (instr.op === 'DIV') {
          lines.push(`          if (a == INT64_MIN && b == -1) { gg_fail(&rt, "RUNTIME_BIGINT_OVERFLOW", "지~랄 정수가 64비트 범위를 초과했어요", ${line}, ${column}); break; }`);
          lines.push('          s.len--; s.data[s.len - 1] = a / b; }');
        } else {
          lines.push('          s.len--; s.data[s.len - 1] = (a == INT64_MIN && b == -1) ? 0 : (a % b); }');
        }
        lines.push(`        ip = ${nextIp};`);
        break;
      case 'EQ':
      case 'LT':
      case 'GT': {
        const cmp = instr.op === 'EQ' ? '==' : instr.op === 'LT' ? '<' : '>';
        lines.push(`        if (!gg_require(&s, &rt, 2, ${line}, ${column})) break;`);
        lines.push(`        { int64_t a = s.data[s.len - 2], b = s.data[s.len - 1]; s.len--; s.data[s.len - 1] = (a ${cmp} b) ? 1 : 0; }`);
        lines.push(`        ip = ${nextIp};`);
        break;
      }
      case 'NOT':
        lines.push(`        if (!gg_require(&s, &rt, 1, ${line}, ${column})) break;`);
        lines.push('        s.data[s.len - 1] = (s.data[s.len - 1] == 0) ? 1 : 0;');
        lines.push(`        ip = ${nextIp};`);
        break;
      case 'STORE':
        lines.push(`        if (!gg_require(&s, &rt, 2, ${line}, ${column})) break;`);
        lines.push(`        if (!gg_mem_set(&mem, &rt, s.data[s.len - 1], s.data[s.len - 2], ${line}, ${column})) break;`);
        lines.push('        s.len -= 2;');
        lines.push(`        ip = ${nextIp};`);
        break;
      case 'LOAD':
        lines.push(`        if (!gg_require(&s, &rt, 1, ${line}, ${column})) break;`);
        lines.push('        s.data[s.len - 1] = gg_mem_get(&mem, s.data[s.len - 1]);');
        lines.push(`        ip = ${nextIp};`);
        break;
      case 'INPUT_INT':
        lines.push('        { int64_t val = 0;');
        lines.push(`          if (!gg_read_int(&rt, &val, ${line}, ${column})) break;`);
        lines.push(`          if (!gg_push(&s, &rt, val, ${line}, ${column})) break; }`);
        lines.push(`        ip = ${nextIp};`);
        break;
      case 'INPUT_CHAR':
        lines.push('        { int64_t cp = 0;');
        lines.push(`          if (!gg_read_char(&rt, &cp, ${line}, ${column})) break;`);
        lines.push(`          if (!gg_push(&s, &rt, cp, ${line}, ${column})) break; }`);
        lines.push(`        ip = ${nextIp};`);
        break;
      case 'PRINT_INT':
        lines.push(`        if (!gg_require(&s, &rt, 1, ${line}, ${column})) break;`);
        lines.push(`        if (!gg_print_int(&rt, s.data[s.len - 1], false, ${line}, ${column})) break;`);
        lines.push('        s.len--;');
        lines.push(`        ip = ${nextIp};`);
        break;
      case 'PRINT_INT_LN':
        lines.push(`        if (!gg_require(&s, &rt, 1, ${line}, ${column})) break;`);
        lines.push(`        if (!gg_print_int(&rt, s.data[s.len - 1], true, ${line}, ${column})) break;`);
        lines.push('        s.len--;');
        lines.push(`        ip = ${nextIp};`);
        break;
      case 'PRINT_CHAR':
        lines.push(`        if (!gg_require(&s, &rt, 1, ${line}, ${column})) break;`);
        lines.push(`        if (!gg_print_char(&rt, s.data[s.len - 1], ${line}, ${column})) break;`);
        lines.push('        s.len--;');
        lines.push(`        ip = ${nextIp};`);
        break;
      case 'JZ':
        lines.push(`        if (!gg_require(&s, &rt, 1, ${line}, ${column})) break;`);
        lines.push(`        ip = (s.data[--s.len] == 0) ? (size_t)${Number(instr.operand)} : (size_t)${nextIp};`);
        break;
      case 'JZ_PEEK':
        lines.push(`        if (!gg_require(&s, &rt, 1, ${line}, ${column})) break;`);
        lines.push(`        ip = (s.data[s.len - 1] == 0) ? (size_t)${Number(instr.operand)} : (size_t)${nextIp};`);
        break;
      case 'JMP':
        lines.push(`        ip = (size_t)${Number(instr.operand)};`);
        break;
      case 'HALT':
        lines.push('        rt.halted = true;');
        break;
    }

    lines.push('        steps++;');
    lines.push('        break;');
    lines.push('      }');
  }

  lines.push('    }');
  lines.push('  }');
  lines.push('');
  lines.push('  (void)line_tbl;');
  lines.push('  (void)col_tbl;');
  lines.push('  free(s.data);');
  lines.push('  free(mem.entries);');
  lines.push('  return rt.failed ? 1 : 0;');
  lines.push('}');
  lines.push('');

  return { code: lines.join('\n'), warnings };
}

export function emitC(program: CompiledProgram, options: EmitOptions = {}): string {
  return emitCWithWarnings(program, options).code;
}

export function compileToTarget(
  source: string,
  target: EmitTarget,
  options: EmitOptions = {},
): EmitResult {
  const { tokens, diagnostics: lexDiagnostics } = tokenize(source);
  const program = parse(tokens, lexDiagnostics);
  const extension: '.mjs' | '.c' = target === 'js' ? '.mjs' : '.c';

  if (program.diagnostics.length > 0) {
    return {
      target,
      code: '',
      extension,
      diagnostics: program.diagnostics,
      warnings: [],
    };
  }

  if (target === 'js') {
    return {
      target,
      code: emitJavaScript(program, options),
      extension,
      diagnostics: [],
      warnings: [],
    };
  }

  const emitted = emitCWithWarnings(program, options);
  return {
    target,
    code: emitted.code,
    extension,
    diagnostics: [],
    warnings: emitted.warnings,
  };
}
